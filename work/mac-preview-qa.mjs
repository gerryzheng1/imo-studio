import {chromium} from 'playwright';
import {pathToFileURL} from 'node:url';
import fs from 'node:fs/promises';

const out='C:/Users/bridge/.codex/visualizations/2026/10/18/01a14ed2-8069-7323-8d63-b00192b7860f';
const browser=await chromium.launch({channel:'msedge',headless:true});
const page=await browser.newPage({viewport:{width:1024,height:950},deviceScaleFactor:1});
const errors=[];
page.on('pageerror',error=>errors.push(String(error)));
await page.emulateMedia({colorScheme:'light',reducedMotion:'reduce'});
await page.goto(pathToFileURL(out+'/imo-macos-preview-rendered.html').href);
const frame=page.frameLocator('#codex-visualization');
await frame.locator('.im-window').waitFor();
const contentFrame=page.frames().find(f=>f.parentFrame());
await contentFrame.addScriptTag({content:await fs.readFile('node_modules/lucide/dist/umd/lucide.js','utf8')});
await contentFrame.evaluate(()=>lucide.createIcons({attrs:{width:17,height:17}}));
await page.waitForTimeout(350);
async function capture(name,width){
  await page.setViewportSize({width,height:1000});
  await page.waitForTimeout(120);
  await frame.locator('#imo-macos-preview').screenshot({path:out+'/'+name+'.png'});
  return await frame.locator('#imo-macos-preview').evaluate(root=>({width:root.clientWidth,scroll:root.scrollWidth,height:root.getBoundingClientRect().height,icons:root.querySelectorAll('svg').length,buttons:root.querySelectorAll('button').length}));
}
const result={};
result.desktop=await capture('preview-desktop',1024);
await frame.getByRole('button',{name:'上海 Shanghai CN SGH'}).count().catch(()=>0);
await frame.locator('[data-im-action="port"][data-port="2"]').click();
if(!await frame.locator('h1').textContent().then(t=>t.includes('上海')))throw new Error('Port selection failed');
await frame.locator('[data-im-action="port"][data-port="1"]').click();
await frame.getByRole('searchbox',{name:'搜索船员'}).fill('Jr.');
if(await frame.locator('#im-people-rows tr').count()!==1)throw new Error('Search failed');
await frame.getByRole('searchbox',{name:'搜索船员'}).fill('');
await frame.locator('[data-im-action="person"][data-person="4"]').first().click();
await frame.locator('#im-edit-rank').selectOption('Jr. 3rd Off');
await frame.locator('#im-edit-name').fill('ZHENG, XIAOTIAN');
await frame.locator('[data-im-action="commit-person"]').click();
await frame.locator('[data-im-action="tab"][data-tab="stores"]').click();
result.stores=await capture('preview-stores',1024);
await frame.getByRole('button',{name:'伙食估算',exact:true}).click();
await frame.locator('#im-food-people').fill('21');
await frame.locator('#im-food-days').fill('7');
await frame.getByRole('button',{name:'计算示例'}).click();
if(!await frame.locator('#im-food-result').textContent().then(t=>t.includes('58.8')))throw new Error('Estimate failed');
await frame.getByRole('button',{name:'总设置',exact:true}).click();
if(await frame.locator('.im-settings-page input[type=checkbox]:checked').count()!==3)throw new Error('Defaults failed');
result.settings=await capture('preview-settings',1024);
await frame.getByLabel('界面外观',{exact:true}).selectOption('深色');
result.dark=await capture('preview-dark',1024);
await frame.getByLabel('界面外观',{exact:true}).selectOption('浅色');
await frame.locator('[data-im-action="page"][data-page="workspace"]').click();
await frame.locator('[data-im-action="tab"][data-tab="people"]').click();
result.mobile=await capture('preview-mobile',390);
await frame.getByRole('button',{name:'检查并生成',exact:true}).click();
if(!await frame.getByRole('dialog').isVisible())throw new Error('Review failed');
await frame.getByRole('button',{name:'返回工作台',exact:true}).click();
result.narrow=await capture('preview-narrow',320);
result.errors=errors;
if(errors.length)throw new Error(errors.join('\n'));
for(const [name,item] of Object.entries(result))if(item&&item.width&&item.scroll>item.width+1)throw new Error(name+' overflow '+JSON.stringify(item));
await fs.writeFile(out+'/preview-qa.json',JSON.stringify(result,null,2));
console.log(JSON.stringify(result,null,2));
